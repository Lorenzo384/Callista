    private JMenuBar createMenuBar(ColorPalette activePalette) {
        JMenuItem exit = new JMenuItem("Salir");
        exit.addActionListener(e -> dispatchEvent(new WindowEvent(this, WindowEvent.WINDOW_CLOSING)));
        JMenu file = new JMenu("Archivo");
        file.add(exit);

        JMenu palettes = new JMenu("Paleta de colores");
        ButtonGroup paletteGroup = new ButtonGroup();
        for (ColorPalette palette : ColorPalette.values()) {
            JRadioButtonMenuItem item = new JRadioButtonMenuItem(palette.getDisplayName(), palette == activePalette);
            item.addActionListener(e -> changePalette(palette));
            paletteGroup.add(item);
            palettes.add(item);
        }
        JMenu appearance = new JMenu("Apariencia");
        appearance.add(palettes);

        JMenuItem syntax = new JMenuItem("Cómo escribir expresiones");
        syntax.addActionListener(e -> showSyntaxHelp());
        JMenuItem about = new JMenuItem("Acerca de Callista");
        about.addActionListener(e -> JOptionPane.showMessageDialog(this,
                "Callista 0.1\nCalculadora de Cálculo II\nProgramación II · Cálculo II",
                "Acerca de Callista", JOptionPane.INFORMATION_MESSAGE));
        JMenu help = new JMenu("Ayuda");
        help.add(syntax);
        help.add(about);

        JMenuBar menuBar = new JMenuBar();
        menuBar.add(file);
        menuBar.add(appearance);
        menuBar.add(help);
        return menuBar;
    }

    /**
     * Cambia la paleta al momento, sin reiniciar, y la recuerda para la
     * próxima vez. Es puramente visual: no pasa por el controlador.
     */
    private void changePalette(ColorPalette palette) {
        palette.install();
        FlatLaf.updateUI();
        resultPanel.setColors(palette.getResultBackground(), palette.getResultForeground());
        palette.save(ColorPalette.userPreferences());
    }

    private void showSyntaxHelp() {
        JTextArea text = new JTextArea("""
                Operaciones     +  -  *  /  ^          3*x^2 - 1
                Multiplicación  puede omitirse         3x, 2sen(x), (x+1)(x-1)
                Potencias       de derecha a izquierda 2^3^2 = 2^9
                Signo           -x^2 = -(x^2)          (-x)^2 = x^2
                Constantes      pi o π, e              2pi, e^x
                Funciones       sen cos tan cot sec csc
                                arcsen arccos arctan
                                senh cosh tanh
                                exp ln log raiz abs
                Paréntesis      siempre en funciones   sen(x), no sen x
                Potencia de f.  después del paréntesis sen(x)^2, no sen^2(x)
                Decimales       con punto              0.5
                Ángulos         en radianes
                """);
        text.setFont(ViewStyles.MATH_SMALL_FONT);
        text.setEditable(false);
        text.setOpaque(false);
        JOptionPane.showMessageDialog(this, text, "Cómo escribir expresiones", JOptionPane.PLAIN_MESSAGE);
    }

    /**
     * Muestra el nombre de cada operación y marca las que aún no están disponibles.
     */
    private class OperationRenderer extends DefaultListCellRenderer {
        @Override
        public Component getListCellRendererComponent(JList<?> list, Object value, int index,
                                                      boolean isSelected, boolean cellHasFocus) {
            super.getListCellRendererComponent(list, value, index, isSelected, cellHasFocus);
            if (value instanceof OperationType operation && !availableOperations.contains(operation)) {
                setText(operation.getDisplayName() + " (próximamente)");
                if (!isSelected) {
                    setForeground(ViewStyles.secondaryTextColor());
                }
            }
            return this;
        }
    }
