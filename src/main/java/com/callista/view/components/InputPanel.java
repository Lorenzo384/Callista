    /**
     * Inserta texto en la posición del cursor. Si el texto termina en «(»
     * se cierra el paréntesis automáticamente y el cursor queda dentro;
     * si había texto seleccionado, queda como argumento: sen(selección).
     */
    public void insert(String text) {
        int start = expressionField.getSelectionStart();
        if (text.endsWith("(")) {
            String selected = expressionField.getSelectedText();
            String argument = selected != null ? selected : "";
            expressionField.replaceSelection(text + argument + ")");
            expressionField.setCaretPosition(start + text.length() + argument.length());
        } else {
            expressionField.replaceSelection(text);
            expressionField.setCaretPosition(start + text.length());
        }
        expressionField.requestFocusInWindow();
    }

    /**
     * Borra la selección o, si no hay, el carácter anterior al cursor.
     */
    public void deleteBeforeCaret() {
        int caret = expressionField.getCaretPosition();
        if (expressionField.getSelectedText() != null) {
            expressionField.replaceSelection("");
        } else if (caret > 0) {
            try {
                expressionField.getDocument().remove(caret - 1, 1);
            } catch (BadLocationException e) {
                throw new IllegalStateException(e);
            }
        }
        expressionField.requestFocusInWindow();
    }

    public void clear() {
        expressionField.setText("");
        clearInterpretation();
        expressionField.requestFocusInWindow();
    }

    public void showInterpretation(String expression) {
        interpretationArea.setForeground(defaultForeground);
        interpretationArea.setText(INTERPRETATION_PREFIX + expression);
    }

    public void showError(String message) {
        interpretationArea.setForeground(ViewStyles.ERROR_COLOR);
        interpretationArea.setText(message);
    }

    public void clearInterpretation() {
        showInterpretation("—");
    }

    /**
     * Lleva el cursor a una posición del texto, contando desde 1.
     */
    public void moveCaretTo(int position) {
        int index = Math.clamp(position - 1L, 0, expressionField.getText().length());
        expressionField.requestFocusInWindow();
        expressionField.setCaretPosition(index);
    }

